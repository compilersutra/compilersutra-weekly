"""Render a Saturday weekly Markdown issue from source-backed stories."""

from __future__ import annotations

from collections import defaultdict
from pathlib import Path

from csweekly.analyzers.hotspots import path_hotspots, score_by_hotspot
from csweekly.models import Story, WeeklyIssue, Window
from csweekly.processors.dedupe import dedupe_stories
from csweekly.window import publish_saturday

# Publication taxonomy (bucket → source categories)
SECTION_GROUPS: list[tuple[str, list[str]]] = [
    ("CPU compilers (LLVM, GCC)", ["llvm", "gcc", "cpu"]),
    ("IR & compiler infra (MLIR)", ["mlir"]),
    ("GPU compilers (open source)", ["gpu"]),
    ("AI / DL compilers", ["ai", "tvm"]),  # tvm kept for older JSON
    ("Research papers", ["research"]),
]


def build_issue(window: Window, stories: list[Story], *, title: str | None = None) -> WeeklyIssue:
    unique = dedupe_stories(stories)
    hot = path_hotspots(unique)
    score_by_hotspot(unique, hot)
    sections: dict[str, list[Story]] = defaultdict(list)
    for story in unique:
        sections[story.category].append(story)
    for cat in sections:
        sections[cat].sort(
            key=lambda s: (
                -s.relevance_score,
                -(s.published_at or s.discovered_at).timestamp(),
            )
        )
    pub = publish_saturday(window)
    return WeeklyIssue(
        title=title or f"CompilerSutra Weekly — {pub.isoformat()}",
        published_on=pub,
        window=window,
        stories=unique,
        sections=dict(sections),
        hotspots={"paths": hot},
    )


def render_markdown(issue: WeeklyIssue) -> str:
    lines: list[str] = [
        f"# {issue.title}",
        "",
        f"**Reporting window:** {issue.window.label} ({issue.window.timezone}, Fri→Fri, end exclusive)",
        f"**Published:** {issue.published_on.isoformat()} (Saturday)",
        "",
        "> Source-backed findings only. Summaries stay factual; we do not invent technical details.",
        ">",
        "> **Scope:** CPU (LLVM/GCC) · MLIR · GPU (**open source only**) · AI/DL compilers · research. "
        "Proprietary CUDA/toolkit internals are out of scope.",
        "",
        "## This Week in Compiler Engineering",
        "",
        f"- Stories collected: **{len(issue.stories)}** (after dedupe)",
        f"- Window: `{issue.window.start.isoformat()}` → `{issue.window.end.isoformat()}`",
        "",
    ]
    if issue.hotspots.get("paths"):
        lines.extend(["## Churn hotspots (paths)", ""])
        for path, count in issue.hotspots["paths"][:12]:
            lines.append(f"- `{path}` — {count} commits touching path")
        lines.append("")

    known_cats: set[str] = set()
    for _, cats in SECTION_GROUPS:
        known_cats.update(cats)

    for heading, cats in SECTION_GROUPS:
        bucket: list[Story] = []
        for cat in cats:
            bucket.extend(issue.sections.get(cat) or [])
        if not bucket:
            continue
        bucket.sort(
            key=lambda s: (
                -s.relevance_score,
                -(s.published_at or s.discovered_at).timestamp(),
            )
        )
        lines.extend([f"## {heading}", ""])
        for story in bucket[:50]:
            lines.extend(_story_bullets(story))
        lines.append("")

    for cat, bucket in sorted(issue.sections.items()):
        if cat in known_cats or not bucket:
            continue
        lines.extend([f"## {cat}", ""])
        for story in bucket[:40]:
            lines.extend(_story_bullets(story))
        lines.append("")

    lines.extend(
        [
            "## CompilerSutra Perspective",
            "",
            "_Editorial notes go here. Keep them clearly separate from source facts._",
            "",
            "## What to Watch Next Week",
            "",
            "- Follow-up merges in the hottest paths above",
            "- Downstream releases that absorb this week's commits",
            "",
            "---",
            "",
            "Generated by [compilersutra-weekly](https://github.com/aabhinavg1/compilersutra-weekly). "
            "Hosted independently; [CompilerSutra](https://www.compilersutra.com/) links out only. "
            "Original sources linked above — do not republish copyrighted articles wholesale.",
            "",
        ]
    )
    return "\n".join(lines)


def write_issue(issue: WeeklyIssue, reports_dir: Path) -> Path:
    year_dir = reports_dir / f"{issue.published_on.year}"
    year_dir.mkdir(parents=True, exist_ok=True)
    path = year_dir / f"{issue.published_on.isoformat()}.md"
    path.write_text(render_markdown(issue), encoding="utf-8")
    return path


def _story_bullets(story: Story) -> list[str]:
    when = story.published_at.date().isoformat() if story.published_at else "unknown-date"
    lines = [
        f"- **{story.title}**",
        f"  - Source: [{story.source_org}]({story.source_url}) · {when} · `{story.evidence_kind.value}`",
        f"  - Fact: {story.summary}",
    ]
    if story.related_ref:
        lines.append(f"  - Ref: `{story.related_ref[:48]}`")
    return lines
